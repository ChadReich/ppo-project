import torch
import torch.nn as nn


class Actor(nn.Module):

    def __init__(self, observation_size, action_size, hidden_size=64):
        super().__init__()

        self.network = nn.Sequential(
            nn.Linear(observation_size, hidden_size),
            nn.Tanh(),
            nn.Linear(hidden_size, hidden_size),
            nn.Tanh(),
            nn.Linear(hidden_size, action_size)
        )

    def forward(self, observation):

        logits = self.network(observation)

        return logits


class Critic(nn.Module):

    def __init__(self, observation_size, hidden_size=64):
        super().__init__()

        self.network = nn.Sequential(
            nn.Linear(observation_size, hidden_size),
            nn.Tanh(),
            nn.Linear(hidden_size, hidden_size),
            nn.Tanh(),
            nn.Linear(hidden_size, 1)
        )

    def forward(self, observation):

        value = self.network(observation)

        # Remove the final size-1 dimension so values have shape [batch_size]
        value = value.squeeze(-1)

        return value

def collect_rollout(env, actor, critic, observation, num_steps):
    """
    Collect num_steps transitions with the current policy.

    The current observation is passed in and returned, so consecutive rollouts
    continue the same episodes rather than resetting.
    """

    states = []
    actions = []
    rewards = []
    old_log_probs = []
    values = []
    next_values = []
    terminateds = []
    truncateds = []

    # Rollout quantities are data generated by the current policy, not part of
    # the computation graph. The stored old log-probabilities become the fixed
    # denominator of the PPO ratio.
    with torch.no_grad():

        for step in range(num_steps):

            observation_tensor = torch.as_tensor(observation, dtype=torch.float32)
            observation_tensor = observation_tensor.unsqueeze(0)

            logits = actor(observation_tensor)
            action_distribution = torch.distributions.Categorical(logits=logits)

            action_tensor = action_distribution.sample()
            old_log_prob = action_distribution.log_prob(action_tensor)
            value = critic(observation_tensor)

            next_observation, reward, terminated, truncated, info = env.step(
                action_tensor.item()
            )

            # Value of the state the environment actually moved to, computed
            # before any reset. On truncation this is the correct bootstrap.
            # On termination GAE multiplies it by zero.
            next_observation_tensor = torch.as_tensor(
                next_observation, dtype=torch.float32
            )
            next_observation_tensor = next_observation_tensor.unsqueeze(0)
            next_value = critic(next_observation_tensor)

            states.append(observation_tensor.squeeze(0))
            actions.append(action_tensor.squeeze(0))
            rewards.append(reward)
            old_log_probs.append(old_log_prob.squeeze(0))
            values.append(value.squeeze(0))
            next_values.append(next_value.squeeze(0))
            terminateds.append(terminated)
            truncateds.append(truncated)

            # The episode is over either way, so reset on both flags.
            # Only GAE needs to tell them apart.
            if terminated or truncated:
                next_observation, info = env.reset()

            observation = next_observation

    rollout = {
        "states": torch.stack(states),
        "actions": torch.stack(actions),
        "rewards": torch.as_tensor(rewards, dtype=torch.float32),
        "old_log_probs": torch.stack(old_log_probs),
        "values": torch.stack(values),
        "next_values": torch.stack(next_values),
        "terminateds": torch.as_tensor(terminateds, dtype=torch.float32),
        "truncateds": torch.as_tensor(truncateds, dtype=torch.float32),
    }

    return rollout, observation




def compute_gae(rollout, gamma, gae_lambda):

    rewards = rollout["rewards"]
    values = rollout["values"]
    next_values = rollout["next_values"]
    terminateds = rollout["terminateds"]
    truncateds = rollout["truncateds"]

    num_steps = rewards.shape[0]

    advantages = torch.zeros_like(rewards)

    # Advantage beyond the end of the rollout
    next_advantage = 0.0

    for t in reversed(range(num_steps)):

        # Bootstrap only stops at a true terminal state
        bootstrap_mask = 1.0 - terminateds[t]

        delta = (
            rewards[t]
            + gamma * bootstrap_mask * next_values[t]
            - values[t]
        )

        # GAE recursion stops at either type of episode boundary
        episode_ended = torch.maximum(
            terminateds[t],
            truncateds[t]
        )

        continue_mask = 1.0 - episode_ended

        advantage = (
            delta
            + gamma
            * gae_lambda
            * continue_mask
            * next_advantage
        )

        advantages[t] = advantage
        next_advantage = advantage

    # Lambda-return targets for the critic
    returns = advantages + values

    return advantages, returns

def normalise_advantages(advantages):

    advantage_mean = advantages.mean()
    advantage_std = advantages.std()

    normalised_advantages = (
        advantages - advantage_mean
    ) / (
        advantage_std + 1e-8
    )

    return normalised_advantages

def compute_ppo_losses(
    actor,
    critic,
    rollout,
    advantages,
    returns,
    clip_epsilon
):

    states = rollout["states"]
    actions = rollout["actions"]
    old_log_probs = rollout["old_log_probs"]

    # Re-evaluate the stored actions using the current policy
    logits = actor(states)

    action_distribution = torch.distributions.Categorical(
        logits=logits
    )

    new_log_probs = action_distribution.log_prob(actions)

    # PPO probability ratio
    log_ratio = new_log_probs - old_log_probs
    ratios = torch.exp(log_ratio)

    # Unclipped PPO objective
    unclipped_objective = ratios * advantages

    # Clipped PPO objective
    clipped_ratios = torch.clamp(
        ratios,
        1.0 - clip_epsilon,
        1.0 + clip_epsilon
    )

    clipped_objective = clipped_ratios * advantages

    policy_objective = torch.minimum(
        unclipped_objective,
        clipped_objective
    )

    # PyTorch minimises losses
    policy_loss = -policy_objective.mean()

    # Re-evaluate state values using the current critic
    new_values = critic(states)

    value_loss = 0.5 * (
        (new_values - returns) ** 2
    ).mean()

    # Mean entropy of the current policy
    entropy = action_distribution.entropy().mean()

    results = {
        "policy_loss": policy_loss,
        "value_loss": value_loss,
        "entropy": entropy,
        "ratios": ratios,
        "new_log_probs": new_log_probs,
        "new_values": new_values,
        "unclipped_objective": unclipped_objective,
        "clipped_objective": clipped_objective
    }

    return results


def update_ppo(
    actor,
    critic,
    actor_optimizer,
    critic_optimizer,
    rollout,
    advantages,
    returns,
    clip_epsilon,
    entropy_coefficient,
    update_epochs,
    minibatch_size,
    max_grad_norm
):

    num_steps = rollout["states"].shape[0]

    # Reuse the same rollout for several PPO epochs
    for epoch in range(update_epochs):

        # Randomly shuffle the rollout indices at the start of each epoch to create minibatches
        indices = torch.randperm(num_steps)

        # Split the rollout into minibatches
        for start in range(0, num_steps, minibatch_size):

            # Select a minibatch of rollout data
            end = min(start + minibatch_size, num_steps)
            minibatch_indices = indices[start:end]

            # Select the transitions corresponding to the minibatch indices
            # old_log_probs remain the probabilities of the actions taken under the old policy, 
            # which are fixed for the PPO ratio
            minibatch_rollout = {
                "states": rollout["states"][minibatch_indices],
                "actions": rollout["actions"][minibatch_indices],
                "old_log_probs": rollout["old_log_probs"][minibatch_indices]
            }

            # Advantages and critic targets were calculated from the 
            # original rollout and remain fixed for all PPO epochs
            minibatch_advantages = advantages[minibatch_indices]
            minibatch_returns = returns[minibatch_indices]

            # Recalculate the PPO losses for the minibatch using the current actor and critic
            # The current policy changes after each optimiser step,
            # while old_log_probs remain fixed for the entire update
            results = compute_ppo_losses(
                actor,
                critic,
                minibatch_rollout,
                minibatch_advantages,
                minibatch_returns,
                clip_epsilon
            )

            # Maximise the clipped PPO objective and the policy entropy, while minimising the critic loss
            # PyTorch minimises losses, so we negate the policy objective and entropy
            # The entropy term encourages exploration by penalising low-entropy policies
            actor_loss = (
                results["policy_loss"]
                - entropy_coefficient * results["entropy"]
            )

            # Critic is trained separately against the lambda-return targets, which are fixed
            critic_loss = results["value_loss"]

            # Update the actor
            actor_optimizer.zero_grad()
            actor_loss.backward()

            torch.nn.utils.clip_grad_norm_(actor.parameters(), max_grad_norm)
            actor_optimizer.step()

            # Update the critic 
            critic_optimizer.zero_grad()
            critic_loss.backward()

            torch.nn.utils.clip_grad_norm_(critic.parameters(), max_grad_norm)
            critic_optimizer.step()